"""Request bodies (what the frontends send). Validation errors come back as HTTP 422 automatically."""
from datetime import datetime
from typing import Literal, Optional, Union

from pydantic import BaseModel, Field

Severity = Literal["UNKNOWN", "LOW", "MEDIUM", "HIGH", "CRITICAL"]


class LoginRequest(BaseModel):
    username: str
    password: str


class IncidentCreate(BaseModel):
    client_request_id: Optional[str] = Field(
        None, max_length=100,
        description="A unique ID generated by the app (e.g. a UUID). Re-sending the same ID returns the same "
                    "incident instead of creating a duplicate.")
    latitude: Optional[float] = Field(None, ge=-90, le=90, description="Leave out if GPS is unavailable.")
    longitude: Optional[float] = Field(None, ge=-180, le=180)
    reported_at: Optional[datetime] = Field(None, description="Device timestamp (UTC).")
    severity: Severity = "UNKNOWN"
    notes: Optional[str] = Field(None, max_length=1000)

    model_config = {"json_schema_extra": {"example": {
        "client_request_id": "7f1c2b9e-demo-0001", "latitude": 28.4744, "longitude": 77.4900,
        "reported_at": "2026-11-25T17:42:10Z", "severity": "HIGH"}}}


class ScanSubmit(BaseModel):
    scan_data: Union[list[float], str] = Field(
        ..., description="EITHER a list of 128 numbers (face embedding) OR a base64 JPEG/PNG image.")
    face_detected: bool = Field(True, description="Set false if the app's face check failed.")
    quality_score: Optional[float] = Field(None, ge=0, le=1, description="0-1 image quality from the app.")
    latitude: Optional[float] = Field(None, ge=-90, le=90, description="Updates the incident location if sent.")
    longitude: Optional[float] = Field(None, ge=-180, le=180)
    timestamp: Optional[datetime] = None


class ReviewDecision(BaseModel):
    decision: Literal["CONFIRM", "REJECT"]
    user_id: Optional[str] = Field(None, description="Required for CONFIRM: the candidate a human verified.")
    notes: str = Field(..., min_length=3, max_length=1000, description="How identity was verified.")


class StatusUpdate(BaseModel):
    status: str
    notes: Optional[str] = Field(None, max_length=1000)


class MedicalNoteCreate(BaseModel):
    note_type: Literal["HANDOFF", "TREATMENT", "NOTE"] = "NOTE"
    notes: str = Field(..., min_length=1, max_length=4000)

    model_config = {"json_schema_extra": {"example": {
        "note_type": "HANDOFF",
        "notes": "Demo handoff: GCS 14, BP 110/70, left forearm fracture splinted, IV line in place."}}}


class DispatchRequest(BaseModel):
    ambulance_id: Optional[str] = Field(None, description="Leave out to auto-pick the nearest available.")
    hospital_id: Optional[str] = Field(None, description="Leave out to auto-pick the nearest open ER.")
    notes: Optional[str] = None


class LocationUpdate(BaseModel):
    latitude: float = Field(..., ge=-90, le=90)
    longitude: float = Field(..., ge=-180, le=180)


class AccessTokenRequest(BaseModel):
    expires_minutes: Optional[int] = Field(None, ge=1, le=120, description="Defaults to INCIDENT_TOKEN_MINUTES.")


class ERStatusUpdate(BaseModel):
    er_status: Literal["OPEN", "BUSY", "DIVERTING"]


class EnrollFace(BaseModel):
    scan_data: Union[list[float], str] = Field(..., description="Embedding (list of numbers) or base64 image.")
